"""Copy disk-guard.sh and snapshot-space-saver.sh into node.sh (between the EMBEDDED HELPERS
markers), so `ssh root@$IP 'bash -s' < node.sh` can install them without any other file.
Run after editing either helper:  python3 tools/embed-helpers.py   (--check: exit 1 if stale)"""
import pathlib, sys
root = pathlib.Path(__file__).resolve().parent.parent
BEGIN = "# BEGIN EMBEDDED HELPERS"
END = "# END EMBEDDED HELPERS"
EOFMARK = "SNAPCHAIN_HELPER_EOF"
parts = [BEGIN + " (generated by tools/embed-helpers.py from disk-guard.sh and snapshot-space-saver.sh; do not edit here)"]
for fn, name in (("helper_disk_guard", "disk-guard.sh"), ("helper_space_saver", "snapshot-space-saver.sh")):
    body = (root / name).read_text()
    assert EOFMARK not in body, name
    parts.append(f"{fn}() {{\n  cat <<'{EOFMARK}'\n{body.rstrip(chr(10))}\n{EOFMARK}\n}}")
parts.append(END)
block = "\n".join(parts)
node = (root / "node.sh").read_text()
a, b = node.index(BEGIN), node.index(END) + len(END)
new = node[:a] + block + node[b:]
if "--check" in sys.argv:
    sys.exit(0 if new == node else 1)
(root / "node.sh").write_text(new)
